const parseWords = (text, level) => text.trim().split('\n').map((line) => {
  const [hanzi, pinyin, meaning] = line.split('|');
  return { hanzi, pinyin, meaning, level };
});
const words = [...parseWords(HSK1, 1), ...parseWords(HSK2, 2)];
const knownKey = 'ly_hsk_known_words';
const historyKey = 'ly_hsk_quiz_history';
const bestScoreKey = 'ly_hsk_best_score';
const savedArray = (key) => {
  try {
    const value = JSON.parse(localStorage.getItem(key) || '[]');
    return Array.isArray(value) ? value : [];
  } catch { return []; }
};
const savedKnown = () => savedArray(knownKey);
const savedHistory = () => savedArray(historyKey);

let activeQuiz = [];
let quizIndex = 0;
let quizScore = 0;
let quizAnswers = [];

function renderWords() {
  const query = document.getElementById('vocabSearch').value.trim().toLowerCase();
  const level = document.getElementById('levelFilter').value;
  const known = new Set(savedKnown());
  const filtered = words.filter((word) =>
    (level === 'all' || String(word.level) === level) &&
    `${word.hanzi} ${word.pinyin} ${word.meaning}`.toLowerCase().includes(query)
  );
  document.getElementById('wordCount').textContent = `${filtered.length} words`;
  document.getElementById('vocabRows').innerHTML = filtered.map((word) => `
    <tr>
      <td class="hanzi-cell">${word.hanzi}<button class="sound-btn" type="button" data-speak="${word.hanzi}" aria-label="Hear ${word.hanzi}">▶</button></td>
      <td>${word.pinyin}</td><td>${word.meaning}</td><td>HSK ${word.level}</td>
      <td><label class="known-label"><input type="checkbox" data-known="${word.hanzi}" ${known.has(word.hanzi) ? 'checked' : ''}> Learned</label></td>
    </tr>`).join('');
  updateProgress();
}

function updateProgress() {
  const knownCount = savedKnown().length;
  const history = savedHistory();
  const best = Math.max(Number(localStorage.getItem(bestScoreKey) || 0), history.reduce((max, item) => Math.max(max, item.score), 0));
  document.getElementById('learnedCount').textContent = `${knownCount} / ${words.length}`;
  const learnedPercent = knownCount ? Math.max(1, Math.round(knownCount / words.length * 100)) : 0;
  document.getElementById('learnedBar').style.width = `${learnedPercent}%`;
  document.getElementById('bestScore').textContent = history.length ? `${best}%` : 'Not tested';
  document.getElementById('testCount').textContent = history.length;
}

function startQuiz() {
  const level = document.getElementById('levelFilter').value;
  const pool = words.filter((word) => level === 'all' || String(word.level) === level);
  if (pool.length < 4) return;
  activeQuiz = [...pool].sort(() => Math.random() - 0.5).slice(0, 10);
  quizIndex = 0;
  quizScore = 0;
  quizAnswers = [];
  document.getElementById('quizPanel').hidden = false;
  document.getElementById('quizResult').hidden = true;
  document.getElementById('quizNext').hidden = false;
  renderQuizQuestion();
  document.getElementById('quizPanel').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function renderQuizQuestion() {
  const word = activeQuiz[quizIndex];
  const alternatives = words.filter((item) => item.hanzi !== word.hanzi)
    .sort(() => Math.random() - 0.5).slice(0, 3);
  const options = [...alternatives, word].sort(() => Math.random() - 0.5);
  document.getElementById('quizProgress').textContent = `Question ${quizIndex + 1} of ${activeQuiz.length}`;
  document.getElementById('quizBar').style.width = `${quizIndex / activeQuiz.length * 100}%`;
  document.getElementById('quizPrompt').innerHTML = `<span class="quiz-hanzi">${word.hanzi}</span><span class="quiz-pinyin">${word.pinyin}</span>`;
  document.getElementById('quizOptions').innerHTML = options.map((option) => `
    <label class="quiz-option"><input type="radio" name="vocabAnswer" value="${option.hanzi}"><span>${option.meaning}</span></label>`).join('');
  document.getElementById('quizFeedback').textContent = '';
}

function submitQuizAnswer() {
  const selected = document.querySelector('input[name="vocabAnswer"]:checked');
  if (!selected) {
    document.getElementById('quizFeedback').textContent = 'Choose an answer to continue.';
    return;
  }
  const word = activeQuiz[quizIndex];
  const correct = selected.value === word.hanzi;
  if (correct) quizScore += 1;
  quizAnswers.push({ word, correct });
  document.getElementById('quizFeedback').textContent = correct
    ? 'Correct.'
    : `Not quite. ${word.hanzi} (${word.pinyin}) means “${word.meaning}”.`;
  document.getElementById('quizNext').textContent = quizIndex === activeQuiz.length - 1 ? 'Finish test' : 'Next question';
  document.getElementById('quizNext').dataset.answered = 'true';
}

function nextQuizQuestion() {
  const nextButton = document.getElementById('quizNext');
  if (nextButton.dataset.answered !== 'true') return submitQuizAnswer();
  delete nextButton.dataset.answered;
  quizIndex += 1;
  if (quizIndex < activeQuiz.length) {
    nextButton.textContent = 'Check answer';
    renderQuizQuestion();
    return;
  }
  const score = Math.round(quizScore / activeQuiz.length * 100);
  const history = savedHistory();
  const completedAt = new Date().toISOString();
  history.push({ date: completedAt, score, correct: quizScore, total: activeQuiz.length });
  localStorage.setItem(historyKey, JSON.stringify(history));
  const activity = savedArray('ly_course_activity');
  activity.push({ course: 'HSK vocabulary', courseId: 'hsk', chapter: `${score}% (${quizScore}/${activeQuiz.length})`, chapterId: 'vocabulary-test', passed: score >= 70, score, at: completedAt });
  localStorage.setItem('ly_course_activity', JSON.stringify(activity.slice(-100)));
  const bestScore = Math.max(Number(localStorage.getItem(bestScoreKey) || 0), score);
  localStorage.setItem(bestScoreKey, String(bestScore));
  document.getElementById('quizBar').style.width = '100%';
  document.getElementById('quizNext').hidden = true;
  document.getElementById('quizResult').hidden = false;
  document.getElementById('quizResultScore').textContent = `${score}% (${quizScore}/${activeQuiz.length})`;
  document.getElementById('quizReview').innerHTML = quizAnswers.map(({ word, correct }) =>
    `<li>${correct ? 'Correct' : 'Review'}: <strong>${word.hanzi}</strong> ${word.pinyin} — ${word.meaning}</li>`
  ).join('');
  updateProgress();
}

document.addEventListener('DOMContentLoaded', () => {
  const params = new URLSearchParams(window.location.search);
  if (['1', '2'].includes(params.get('level'))) {
    document.getElementById('levelFilter').value = params.get('level');
  }
  document.getElementById('vocabSearch').addEventListener('input', renderWords);
  document.getElementById('levelFilter').addEventListener('change', renderWords);
  document.getElementById('startQuiz').addEventListener('click', startQuiz);
  document.getElementById('quizNext').addEventListener('click', nextQuizQuestion);
  document.getElementById('vocabRows').addEventListener('change', (event) => {
    const hanzi = event.target.dataset.known;
    if (!hanzi) return;
    const known = new Set(savedKnown());
    event.target.checked ? known.add(hanzi) : known.delete(hanzi);
    localStorage.setItem(knownKey, JSON.stringify([...known]));
    if (event.target.checked) {
      const activity = savedArray('ly_course_activity');
      activity.push({ course: 'HSK vocabulary', courseId: 'hsk', chapter: `Learned ${hanzi}`, chapterId: `word:${hanzi}`, passed: true, score: 100, at: new Date().toISOString() });
      localStorage.setItem('ly_course_activity', JSON.stringify(activity.slice(-100)));
    }
    updateProgress();
  });
  document.getElementById('vocabRows').addEventListener('click', (event) => {
    const button = event.target.closest('[data-speak]');
    if (!button || !('speechSynthesis' in window)) return;
    const utterance = new SpeechSynthesisUtterance(button.dataset.speak);
    utterance.lang = 'zh-CN';
    speechSynthesis.cancel();
    speechSynthesis.speak(utterance);
  });
  renderWords();
  if (params.get('test') === '1') startQuiz();
});
